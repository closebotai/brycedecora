/**
 * URL policy. Encoded here so tests can assert against it rather than against a
 * hard-coded assumption.
 *
 * Three settings must agree or Cloudflare will redirect every indexed URL:
 *   1. astro.config.ts  build.format: 'directory'      -> emits dist/about/index.html
 *   2. astro.config.ts  trailingSlash: 'always'        -> links + canonicals emit /about/
 *   3. wrangler.jsonc   html_handling: force-trailing-slash
 *
 * Changing this after launch means redirecting every indexed URL. Don't.
 */
export const TRAILING_SLASH: 'always' | 'never' = 'always';

/**
 * Routes deliberately excluded from indexing.
 *
 * Single source of truth: consumed by the `@astrojs/sitemap` filter in
 * `astro.config.ts` AND by `<SEO>` when emitting the robots meta tag, so the
 * two can never disagree. `tests/seo/indexability.spec.ts` verifies that every
 * route listed here is both absent from the sitemap and carries `noindex`.
 *
 * Pathnames must be written in canonical form (leading + trailing slash).
 */
export const NOINDEX_ROUTES: readonly string[] = ['/thanks/'];

/** True when the given pathname should be indexed and appear in the sitemap. */
export function isIndexable(pathname: string): boolean {
  return !NOINDEX_ROUTES.includes(normalizePathname(pathname));
}

/**
 * Coerce a pathname or absolute URL into the site's canonical path form:
 * lowercase, leading slash, trailing slash (root stays '/').
 */
export function normalizePathname(input: string): string {
  let path = input;

  // Accept a full URL as well as a bare pathname.
  if (/^https?:\/\//i.test(path)) {
    path = new URL(path).pathname;
  }

  // Strip query and hash -- they are never part of a canonical path.
  path = path.split(/[?#]/)[0] ?? '/';

  path = path.toLowerCase();

  if (!path.startsWith('/')) path = `/${path}`;

  // Paths naming a file (/robots.txt, /404.html, /og/default.png) are already
  // canonical. Appending a slash to them produces a URL that does not exist.
  if (/\.[a-z0-9]+$/i.test(path)) return path;

  if (TRAILING_SLASH === 'always') {
    if (!path.endsWith('/')) path = `${path}/`;
  } else if (path !== '/' && path.endsWith('/')) {
    path = path.slice(0, -1);
  }

  return path;
}
